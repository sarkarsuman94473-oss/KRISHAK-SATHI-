package com.example.data.local.entity

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.example.data.model.NurseryVerificationStatus
import com.example.data.model.PlantKingdomEntry
import com.example.data.model.WbNurseryDirectoryEntry

@Entity(
    tableName = "plant_kingdom",
    indices = [
        Index(value = ["primaryGroup"]),
        Index(value = ["nameEn"]),
        Index(value = ["scientificName"])
    ]
)
data class PlantKingdomEntity(
    @PrimaryKey
    val plantId: String,
    val nameEn: String,
    val nameBn: String,
    val nameHi: String,
    val scientificName: String,
    val primaryGroup: String,
    val secondaryGroupsCsv: String,
    val filterTagsCsv: String,
    val seasonalTagsCsv: String,
    val descriptionEn: String,
    val descriptionBn: String,
    val descriptionHi: String,
    val visualAssetKey: String,
    val customPhotoUri: String,
    val climate: String,
    val temperatureRange: String,
    val soilRequirements: String,
    val sunlight: String,
    val wateringFrequency: String,
    val fertilizerGuidance: String,
    val propagationMethod: String,
    val floweringOrFruitingSeason: String,
    val growthSize: String,
    val indoorOutdoorSuitability: String,
    val plainsHillSuitability: String,
    val commonPestsDiseases: String,
    val careInstructionsEn: String,
    val careInstructionsBn: String,
    val careInstructionsHi: String,
    val verifiedNurseryIdsCsv: String,
    val isRare: Boolean,
    val isVerifiedEntry: Boolean,
    val publicationStatus: String = "PUBLISHED",
    val sourceReference: String,
    val lastVerifiedDate: String,
    val updatedAtMillis: Long
) {
    fun toModel(): PlantKingdomEntry = PlantKingdomEntry(
        plantId = plantId,
        nameEn = nameEn,
        nameBn = nameBn,
        nameHi = nameHi,
        scientificName = scientificName,
        primaryGroup = primaryGroup,
        secondaryGroupsCsv = secondaryGroupsCsv,
        filterTagsCsv = filterTagsCsv,
        seasonalTagsCsv = seasonalTagsCsv,
        descriptionEn = descriptionEn,
        descriptionBn = descriptionBn,
        descriptionHi = descriptionHi,
        visualAssetKey = visualAssetKey,
        customPhotoUri = customPhotoUri,
        climate = climate,
        temperatureRange = temperatureRange,
        soilRequirements = soilRequirements,
        sunlight = sunlight,
        wateringFrequency = wateringFrequency,
        fertilizerGuidance = fertilizerGuidance,
        propagationMethod = propagationMethod,
        floweringOrFruitingSeason = floweringOrFruitingSeason,
        growthSize = growthSize,
        indoorOutdoorSuitability = indoorOutdoorSuitability,
        plainsHillSuitability = plainsHillSuitability,
        commonPestsDiseases = commonPestsDiseases,
        careInstructionsEn = careInstructionsEn,
        careInstructionsBn = careInstructionsBn,
        careInstructionsHi = careInstructionsHi,
        verifiedNurseryIdsCsv = verifiedNurseryIdsCsv,
        isRare = isRare,
        isVerifiedEntry = isVerifiedEntry,
        publicationStatus = publicationStatus,
        sourceReference = sourceReference,
        lastVerifiedDate = lastVerifiedDate,
        updatedAtMillis = updatedAtMillis
    )

    companion object {
        fun fromModel(m: PlantKingdomEntry): PlantKingdomEntity = PlantKingdomEntity(
            plantId = m.plantId,
            nameEn = m.nameEn,
            nameBn = m.nameBn,
            nameHi = m.nameHi,
            scientificName = m.scientificName,
            primaryGroup = m.primaryGroup,
            secondaryGroupsCsv = m.secondaryGroupsCsv,
            filterTagsCsv = m.filterTagsCsv,
            seasonalTagsCsv = m.seasonalTagsCsv,
            descriptionEn = m.descriptionEn,
            descriptionBn = m.descriptionBn,
            descriptionHi = m.descriptionHi,
            visualAssetKey = m.visualAssetKey,
            customPhotoUri = m.customPhotoUri,
            climate = m.climate,
            temperatureRange = m.temperatureRange,
            soilRequirements = m.soilRequirements,
            sunlight = m.sunlight,
            wateringFrequency = m.wateringFrequency,
            fertilizerGuidance = m.fertilizerGuidance,
            propagationMethod = m.propagationMethod,
            floweringOrFruitingSeason = m.floweringOrFruitingSeason,
            growthSize = m.growthSize,
            indoorOutdoorSuitability = m.indoorOutdoorSuitability,
            plainsHillSuitability = m.plainsHillSuitability,
            commonPestsDiseases = m.commonPestsDiseases,
            careInstructionsEn = m.careInstructionsEn,
            careInstructionsBn = m.careInstructionsBn,
            careInstructionsHi = m.careInstructionsHi,
            verifiedNurseryIdsCsv = m.verifiedNurseryIdsCsv,
            isRare = m.isRare,
            isVerifiedEntry = m.isVerifiedEntry,
            publicationStatus = m.publicationStatus.ifBlank { if (m.isVerifiedEntry) "PUBLISHED" else "DRAFT_REVIEW_REQUIRED" },
            sourceReference = m.sourceReference,
            lastVerifiedDate = m.lastVerifiedDate,
            updatedAtMillis = m.updatedAtMillis
        )
    }
}

